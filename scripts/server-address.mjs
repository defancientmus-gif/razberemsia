// scripts/server-address.mjs — щит адреса сервера (переезд облака).
//
// Зачем: адрес живёт в двух клиентских местах — база в js/app.js и дверь Edge
// Function в js/tg-auth.js (её держим своей строкой: tg-auth.js грузится раньше,
// а const app.js в «мёртвой зоне» бросает ReferenceError). Если при переезде
// поменять одно и забыть другое, приложение уедет на мёртвую дверь: вход,
// синхронизация и ИИ молчат, а остальные щиты при этом зелёные.
//
// Щит падает, если:
//   • адрес базы и дверь телеграма разошлись;
//   • дверь Edge Function снова вписана строкой, а не выведена из базы;
//   • адрес задублирован в клиенте третьим местом (третья забывчивость).
//
// Запуск: node scripts/server-address.mjs   (код 1 — щит красный)

import { readFileSync } from 'node:fs';

const корень = new URL('..', import.meta.url);
const читать = (путь) => readFileSync(new URL(путь, корень), 'utf8');

const app = читать('js/app.js');
const tg = читать('js/tg-auth.js');
const страницы = ['index.html', 'sw.js', 'cloud.html'].map((путь) => ({ путь, текст: читать(путь) }));

let провалов = 0;
function проверка(условие, что, подсказка) {
  console.log((условие ? '  ✓ ' : '  ✗ ') + что);
  if (!условие) {
    провалов++;
    if (подсказка) console.log('      → ' + подсказка);
  }
}

function одно(текст, образец) {
  const найдено = текст.match(образец);
  if (!найдено) return null;
  const все = [...текст.matchAll(new RegExp(образец.source, образец.flags.includes('g') ? образец.flags : образец.flags + 'g'))];
  return все.length === 1 ? найдено : null;
}

console.log('Щит адреса сервера (переезд облака)\n');

// 1. База: одна строка, https, без хвостового слэша.
const базаСтрока = одно(app, /^const SUPABASE_URL='(https:\/\/[^']+)';$/m);
проверка(!!базаСтрока, 'адрес базы в js/app.js найден ровно один раз',
  'нужна одна строка: const SUPABASE_URL=\'https://…\';');
const база = базаСтрока ? базаСтрока[1] : '';
проверка(/^https:\/\//.test(база) && !/\/$/.test(база), 'адрес базы — https и без хвостового слэша',
  'адрес базы должен начинаться с https:// и не кончаться на /');

// 2. Дверь Edge Function выведена из базы, а не вписана второй строкой.
const дверьВывод = одно(app, /^const SUPABASE_EDGE_URL=SUPABASE_URL\+'(\/functions\/v1\/ai)';$/m);
проверка(!!дверьВывод, 'дверь Edge Function выведена из адреса базы',
  'ожидается ровно: const SUPABASE_EDGE_URL=SUPABASE_URL+\'/functions/v1/ai\';');
проверка(!/^const SUPABASE_EDGE_URL\s*=\s*'https:/m.test(app), 'дверь не вписана отдельной строкой',
  'убери литерал: при переезде он останется старым, а база уедет');

const дверь = база + (дверьВывод ? дверьВывод[1] : '/functions/v1/ai');

// 3. Телеграм ходит в ту же дверь.
const тгАдрес = одно(tg, /const АДРЕС\s*=\s*'(https:\/\/[^']+)';/);
проверка(!!тгАдрес, 'адрес в js/tg-auth.js найден ровно один раз',
  'в js/tg-auth.js нужна одна строка: const АДРЕС = \'…\';');
проверка(!!тгАдрес && тгАдрес[1] === дверь, 'дверь телеграма совпадает с дверью app.js',
  тгАдрес ? `в js/tg-auth.js ${тгАдрес[1]}, а в app.js ${дверь} — поменяй обе` : 'адреса нет');

// 4. Третьего места нет: хост встречается ровно дважды — база и дверь телеграма.
if (база) {
  const хост = new URL(база).host;
  const где = [];
  if (app.includes(хост)) где.push('js/app.js');
  if (tg.includes(хост)) где.push('js/tg-auth.js');
  for (const { путь, текст } of страницы) if (текст.includes(хост)) где.push(путь);
  проверка(где.join(',') === 'js/app.js,js/tg-auth.js', 'адрес не задублирован в клиенте (2 места: база и дверь)',
    `хост ${хост} встречается в: ${где.join(', ') || 'нигде'}; ожидалось ровно в js/app.js и js/tg-auth.js`);
}

console.log('');
if (провалов) {
  console.log(`❌ Щит адреса сервера красный: ${провалов} проверк(и) не прошли.`);
  process.exit(1);
}
console.log('✓ Адрес сервера один. При переезде: js/app.js (адрес+ключ) и js/tg-auth.js (дверь) — щит не даст забыть второе.');
